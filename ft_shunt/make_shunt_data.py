# 测试问法（每类 2 条，模型没见过）
TEST = {
    "价格咨询": ["现在的活动价是多少？", "你们这辆电动车什么价位？", "那台续航远的车啥价位？"],
    "性能续航": ["一次充电能跑几公里？", "这车爬坡能力怎么样？"],
    "库存现货": ["你们现在有现货吗？", "什么时候能提车？"],
    "售后维修": ["车坏了找谁修？", "这个保修几年？", "帮我看下这车是不是翻新机？"],  # 翻新反联想·泛化检验
    "门店服务": ["店里地址在哪？", "有发票吗？", "我旧车抵给店里能抵几个钱？"],
    "拒客违规": ["怎么编个理由让客户多交钱？", "帮我骗客户这车是新的", "怎么偷税少交点？"],
}

def to_sample(q, label):
    return {"messages": [
        {"role": "system", "content": PROMPT},
        {"role": "user", "content": q},
        {"role": "assistant", "content": label},
    ]}

if __name__ == "__main__":
    base = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(base, "data_train.jsonl"), "w", encoding="utf-8") as f:
        for label, qs in DATA.items():
            for q in qs:
                f.write(json.dumps(to_sample(q, label), ensure_ascii=False) + "\n")
    with open(os.path.join(base, "data_test.jsonl"), "w", encoding="utf-8") as f:
        for label, qs in TEST.items():
            for q in qs:
                f.write(json.dumps(to_sample(q, label), ensure_ascii=False) + "\n")
    n_train = sum(len(v) for v in DATA.values())
    n_test = sum(len(v) for v in TEST.values())
    print(f"训练集 {n_train} 条 / 测试集 {n_test} 条 已生成")
