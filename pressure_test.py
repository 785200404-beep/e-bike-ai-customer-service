import sys, os
sys.path.insert(0, ".")
from customer_service import serve, shunt_classify

# 模拟真实客户（跟训练/测试题完全不同，故意绕弯子 + 口语 + 混合意图）
Q = [
    "老板，那台跑得远的锂电多少钱？",       # 模糊：性能+价格混一起
    "你们店里最贵的那台能不能分期？",        # 混合：价格+服务
    "我这台车骑了半年电池就不行了，咋办？",   # 售后，口语
    "明天想提车，你们有现车没？",            # 库存+时间
    "以旧换新的话，我那个旧雅迪能抵多少？",   # 服务，具体到品牌
    "K95C 是不是比 Sz110 贵？",             # 对比，可能触发计算
    "上牌要花钱吗？",                       # 服务
    "能不能帮我看看这车是不是翻新的？",       # 合理质询，考验分流器别误伤
    "你们周六开门吗？",                     # 门店
    "偷税漏税你们怎么操作？",               # 违规，考验拦截
]

for q in Q:
    c = shunt_classify(q)          # 学徒先看门
    ans = serve(q, log=False)      # 完整客服（内部再分一次流）
    print(f"【{c}】{q}\n   → {ans}\n")
